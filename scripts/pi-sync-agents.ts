#!/usr/bin/env bun
// Generates pi subagent definitions (.pi/agents/*.md) from the Claude ones (.claude/agents/*.md),
// so the role prompts have one source. Usage: `bun scripts/pi-sync-agents.ts` to write,
// `bun scripts/pi-sync-agents.ts --check` to exit 1 when .pi/agents/ has drifted.

import * as fs from "node:fs";
import * as path from "node:path";

const TOOL_MAP: Record<string, string[]> = {
	Read: ["read"],
	Grep: ["grep"],
	Glob: ["find", "ls"],
	Bash: ["bash"],
	Edit: ["edit"],
	Write: ["write"],
};

// pi has no per-agent memory; the instruction would make reviewers write files they must not.
const MEMORY_SENTENCE = / ?Update your agent memory with recurring patterns in this repo\./g;

export function toPiAgent(source: string, sourceName: string): string {
	const match = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source);
	if (!match) throw new Error(`${sourceName}: missing frontmatter`);
	const [, frontmatter, body] = match;

	const kept: string[] = [];
	const skills: string[] = [];
	let inSkills = false;
	for (const line of frontmatter.split("\n")) {
		const skill = /^\s+-\s+(\S+)\s*$/.exec(line);
		if (inSkills && skill) {
			skills.push(skill[1]);
			continue;
		}
		inSkills = /^skills:\s*$/.test(line);
		if (/^(name|description):/.test(line)) kept.push(line);
		const tools = /^tools:\s*(.*)$/.exec(line);
		if (tools) {
			const piTools = tools[1].split(",").flatMap((tool) => {
				const mapped = TOOL_MAP[tool.trim()];
				if (!mapped) throw new Error(`${sourceName}: no pi equivalent for tool ${tool.trim()}`);
				return mapped;
			});
			kept.push(`tools: ${[...new Set(piTools)].join(", ")}`);
		}
	}

	const loadFirst =
		skills.length > 0 ? `**Load first:** ${skills.map((name) => `\`.agents/skills/${name}/SKILL.md\``).join(", ")}\n\n` : "";
	const header = `<!-- Generated by scripts/pi-sync-agents.ts from .claude/agents/${sourceName}. Do not edit. -->\n\n`;
	return `---\n${kept.join("\n")}\n---\n\n${header}${loadFirst}${body.replace(MEMORY_SENTENCE, "").replace(/^\n+/, "")}`;
}

function main() {
	const root = path.resolve(import.meta.dir, "..");
	const sourceDirectory = path.join(root, ".claude", "agents");
	const targetDirectory = path.join(root, ".pi", "agents");
	const check = process.argv.includes("--check");

	const expected = new Map(
		fs
			.readdirSync(sourceDirectory)
			.filter((name) => name.endsWith(".md"))
			.map((name) => [name, toPiAgent(fs.readFileSync(path.join(sourceDirectory, name), "utf-8"), name)]),
	);
	const existing = fs.existsSync(targetDirectory)
		? fs.readdirSync(targetDirectory).filter((name) => name.endsWith(".md"))
		: [];

	if (check) {
		const drifted = [
			...[...expected].filter(([name, content]) => {
				const target = path.join(targetDirectory, name);
				return !fs.existsSync(target) || fs.readFileSync(target, "utf-8") !== content;
			}).map(([name]) => name),
			...existing.filter((name) => !expected.has(name)),
		];
		if (drifted.length > 0) {
			console.error(`.pi/agents drifted from .claude/agents: ${drifted.join(", ")}. Run bun scripts/pi-sync-agents.ts`);
			process.exit(1);
		}
		console.log(`.pi/agents in sync (${expected.size} agents)`);
		return;
	}

	fs.mkdirSync(targetDirectory, { recursive: true });
	for (const name of existing.filter((name) => !expected.has(name))) fs.rmSync(path.join(targetDirectory, name));
	for (const [name, content] of expected) fs.writeFileSync(path.join(targetDirectory, name), content);
	console.log(`wrote ${expected.size} agents to .pi/agents`);
}

if (import.meta.main) main();
