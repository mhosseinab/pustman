import { describe, expect, test } from "bun:test";
import { toPiAgent } from "./pi-sync-agents.ts";

const wrapper = `---
name: gpui-ui-reviewer
description: Reviews GPUI view code. Use after writing UI code.
tools: Read, Grep, Glob, Bash
model: sonnet
color: blue
skills:
  - rust-gpui-ui-ux
  - gpui-actions-keymaps
---

Your full role instructions live in \`.agents/agents/gpui-ui-reviewer.md\`.
`;

const loopRole = `---
name: security-reviewer
description: "Reviewer for auth: secrets, trust boundaries."
tools: Read, Grep, Glob, Bash, Edit, Write
model: opus
memory: project
isolation: worktree
maxTurns: 40
---

# security-reviewer
You do NOT fix anything. Update your agent memory with recurring patterns in this repo.
`;

describe("toPiAgent", () => {
	test("keeps name and description verbatim and maps Claude tools to pi tools", () => {
		const output = toPiAgent(loopRole, "security-reviewer.md");
		expect(output).toContain("name: security-reviewer\n");
		expect(output).toContain('description: "Reviewer for auth: secrets, trust boundaries."\n');
		expect(output).toContain("tools: read, grep, find, ls, bash, edit, write\n");
	});

	test("drops Claude-only fields so the agent inherits the orchestrator's model", () => {
		const frontmatter = toPiAgent(loopRole, "security-reviewer.md").split("---")[1];
		for (const field of ["model:", "memory:", "isolation:", "maxTurns:", "color:"]) {
			expect(frontmatter).not.toContain(field);
		}
	});

	test("turns preloaded skills into a load-first line in the body", () => {
		const output = toPiAgent(wrapper, "gpui-ui-reviewer.md");
		expect(output).not.toContain("skills:");
		expect(output).toContain(
			"**Load first:** `.agents/skills/rust-gpui-ui-ux/SKILL.md`, `.agents/skills/gpui-actions-keymaps/SKILL.md`",
		);
		expect(output).toContain("Your full role instructions live in `.agents/agents/gpui-ui-reviewer.md`.");
	});

	test("removes the agent-memory instruction pi cannot honor", () => {
		expect(toPiAgent(loopRole, "security-reviewer.md")).not.toContain("agent memory");
	});

	test("marks the output as generated from its source", () => {
		expect(toPiAgent(wrapper, "gpui-ui-reviewer.md")).toContain(
			"<!-- Generated by scripts/pi-sync-agents.ts from .claude/agents/gpui-ui-reviewer.md. Do not edit. -->",
		);
	});

	test("rejects an unknown Claude tool instead of silently dropping it", () => {
		expect(() => toPiAgent(wrapper.replace("Bash", "WebFetch"), "x.md")).toThrow("WebFetch");
	});
});
